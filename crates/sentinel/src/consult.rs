//! Autonomous strategy consults (SPEC-P20 §2–§3): pipeline triggers -> consult
//! task -> policy gate -> approved orders back to the pipeline; STRATEGY
//! journal entries.
//!
//! Every piece of this machinery is active only when a strategy engine exists
//! (`ENABLE_STRATEGY` plus a real provider key). With no engine the task is
//! inert and `main` does not spawn it — the pipeline keeps its pre-P20
//! behaviour byte-for-byte, and its `consult_scheduled` alerts for Yellow
//! entries are unchanged.
//!
//! ```text
//! pipeline --ConsultTrigger--> [consult task] --> StrategyEngine::consult
//!    ^                              |                     |
//!    |                       (audit-before-action)       v
//!    |   policy gate (Strategy) <-- Decision -> Intent mapping (bot parity)
//!    +--- ApprovedOrder (mpsc) <--- allow + sized order
//! ```
//!
//! Triggers (SPEC-P20 §2, per SPEC-P07 §5):
//!
//! - (a) Yellow-ENTRY transition per market — sent by the pipeline;
//! - (b) post-reflex review after an executed Orange/Red reduce — pipeline;
//! - (c) periodic portfolio review every `STRATEGY_REVIEW_INTERVAL_SECS`
//!   (default [`DEFAULT_REVIEW_INTERVAL_SECS`]) while any position is at or
//!   above Yellow — an internal timer delivered through the same handler as a
//!   [`ConsultTrigger::Periodic`] value.
//!
//! The strategy engine enforces the per-market rate limit and the hourly/daily
//! budget inside [`StrategyEngine::consult`]; a budget breach yields its
//! synthetic `ESCALATE` outcome, which this task journals and alerts like any
//! other ESCALATE. `NeedsApproval` decisions are journaled and alerted only —
//! the daemon path never shows an approval keyboard (the operator can re-run
//! `/risk` or `/close` by hand).
//!
//! Smart-money context is fetched cache-first through the P09 Nansen client
//! when one is configured (`NANSEN_PAYER_KEY` + `ENABLE_NANSEN`); any error or
//! timeout (capped at [`SM_FETCH_TIMEOUT`]) degrades to
//! [`SmartMoneyContext::unavailable`]. Without a client the context is
//! unavailable, silently.

