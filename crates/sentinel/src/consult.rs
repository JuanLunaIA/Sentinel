    async fn yellow_entry_consult_queues_a_policy_allowed_order_and_journals() {
        let dir = tempfile::tempdir().expect("tempdir");
        let journal = AuditJournal::open(dir.path().join("audit")).expect("open journal");
        let journal = Arc::new(Mutex::new(journal));
        let (trigger_tx, trigger_rx) = mpsc::channel(4);
        let (order_tx, mut order_rx) = mpsc::channel(4);
        let sink = RecordingSink::new();
        let alerts = Arc::clone(&sink.alerts);
        let task = ConsultTask::<MockProvider, NoProvider, RecordingSink>::new(
            Some(mock_engine(vec![reduce_json("1.0")], 0)),
            test_config(&[]),
            fixture_state(eth_position("10", "2500.00", "13560")),
            Some(Arc::clone(&journal)),
            shared_policy(dir.path()),
            Arc::new(Mutex::new(trigger_rx)),
            order_tx,
            sink,
            None,
            3600,
        );
        let (shutdown_tx, shutdown_rx) = watch::channel(false);
        let handle = tokio::spawn(task.run(shutdown_rx));

        trigger_tx
            .send(ConsultTrigger::YellowEntry {
                market_id: MarketId(32),
            })
            .await
            .expect("queue a trigger");

        let approved = tokio::time::timeout(Duration::from_secs(5), order_rx.recv())
            .await
            .expect("an order within the timeout")
            .expect("the channel stays open");
        assert_eq!(approved.decision_id, "s-1");
        assert_eq!(approved.order.market_id, MarketId(32));
        assert_eq!(approved.order.close, CloseSide::CloseLong);
        assert_eq!(approved.order.size, dec("1.000"), "0.1 × 10 quantized");

        // Shutdown and join so every journal write has landed.
        shutdown_tx.send(true).expect("shutdown");
        tokio::time::timeout(Duration::from_secs(5), handle)
            .await
            .expect("task stops")
            .expect("no panic");

        let entries = journal
            .lock()
            .await
            .read_entries(0, 10)
            .expect("read journal");
        assert_eq!(entries.len(), 2, "intent before, outcome after");
        assert_eq!(entries[0].trigger, Trigger::Strategy);
        assert_eq!(entries[0].execution["status"], "pending");
        assert_eq!(entries[0].decision["action"], "consult");
        assert_eq!(entries[1].trigger, Trigger::Strategy);
        assert_eq!(entries[1].execution["status"], "queued");
        assert_eq!(entries[1].policy_verdict["verdict"], "allow");
        assert_eq!(entries[1].decision["decision_id"], "s-1");
        assert!(
            alerts.lock().expect("alerts lock").is_empty(),
            "no alert for a quiet Yellow allow"
        );
    }

    #[tokio::test]
    async fn needs_approval_decision_alerts_without_an_order() {
        let dir = tempfile::tempdir().expect("tempdir");
        let (trigger_tx, trigger_rx) = mpsc::channel(4);
        let (order_tx, mut order_rx) = mpsc::channel(4);
        let sink = RecordingSink::new();
        let alerts = Arc::clone(&sink.alerts);
        let task = ConsultTask::<MockProvider, NoProvider, RecordingSink>::new(
            Some(mock_engine(vec![reduce_json("1.0")], 0)),
            // Approval threshold below the 2500 USD notional forces NeedsApproval.
            test_config(&[("REQUIRE_APPROVAL_ABOVE_USD", "100")]),
            fixture_state(eth_position("10", "2500.00", "13560")),
            None,
            shared_policy(dir.path()),
            Arc::new(Mutex::new(trigger_rx)),
            order_tx,
            sink,
            None,
            3600,
        );
        let (shutdown_tx, shutdown_rx) = watch::channel(false);
        let handle = tokio::spawn(task.run(shutdown_rx));

        trigger_tx
            .send(ConsultTrigger::YellowEntry {
                market_id: MarketId(32),
            })
            .await
            .expect("queue a trigger");

        // Poll for the alert, then stop the task.
        let mut captured = Vec::new();
        for _ in 0..50 {
            captured = alerts.lock().expect("alerts lock").clone();
            if !captured.is_empty() {
                break;
            }
            tokio::time::sleep(Duration::from_millis(10)).await;
        }
        assert_eq!(captured.len(), 1, "one alert for the needs-approval case");
        assert!(captured[0].text.contains("needs approval"));
        assert!(
            matches!(&captured[0].kind, AlertKind::StrategyDecision { .. }),
            "alert kind: {:?}",
            captured[0].kind
        );
        assert_eq!(captured[0].market_id, Some(MarketId(32)));
        assert!(order_rx.try_recv().is_err(), "no keyboard, no order");

        shutdown_tx.send(true).expect("shutdown");
        tokio::time::timeout(Duration::from_secs(5), handle)
            .await
            .expect("task stops")
            .expect("no panic");
    }
