/// Periodic portfolio-review cadence when `STRATEGY_REVIEW_INTERVAL_SECS` is
/// unset (seconds, SPEC-P20 §2c).
pub const DEFAULT_REVIEW_INTERVAL_SECS: u64 = 1800;

/// Hard cap on one smart-money fetch (SPEC-P20 §2.2): a slow paid call must
/// never stall the consult loop.
const SM_FETCH_TIMEOUT: Duration = Duration::from_secs(5);

/// Journal scan window used to summarise recent reflex actions.
const REFLEX_SCAN_LIMIT: usize = 500;

/// Maximum number of reflex actions rendered into the prompt summary.
const REFLEX_SUMMARY_LIMIT: usize = 6;

/// One reason the consult task should run a strategy consult.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConsultTrigger {
    /// A market just entered the Yellow tier (SPEC-P07 §5a).
    YellowEntry {
        /// Market that entered Yellow.
        market_id: MarketId,
    },
    /// A reflex reduce executed at Orange or Red; review the position
    /// (SPEC-P07 §5b).
    PostReflexReduce {
        /// Market the executed reduce targeted.
        market_id: MarketId,
        /// Tier at reflex-decision time (Orange or Red).
        tier: RiskTier,
    },
    /// Periodic portfolio review tick (SPEC-P20 §2c); generated by the
    /// consult task's own timer, never by the pipeline.
    Periodic,
}

impl ConsultTrigger {
    /// Stable label used in logs and journal documents.
    pub fn label(&self) -> &'static str {
        match self {
            ConsultTrigger::YellowEntry { .. } => "yellow_entry",
            ConsultTrigger::PostReflexReduce { .. } => "post_reflex_reduce",
            ConsultTrigger::Periodic => "periodic",
        }
    }
}

/// An allowed, sized strategy order travelling from the consult task to the
/// pipeline (SPEC-P20 §2.4). The pipeline submits it through its existing
/// executor/event/alert path and journals the STRATEGY outcome with the
/// execution status.
#[derive(Debug, Clone, PartialEq)]
pub struct ApprovedOrder {
    /// Consult decision correlation id (`s-<n>`).
    pub decision_id: String,
    /// Sized reduce-only order.
    pub order: OrderRequest,
}

/// The supervised consult task (one per daemon; built by `main`).
///
/// Generic over the engine's provider slots and the alert sink so tests can
/// drive it with mock providers and a recording sink.
pub struct ConsultTask<P: Provider, F: Provider, S> {
    /// Shared strategy engine (`None` makes the task inert).
    pub engine: Option<Arc<StrategyEngine<P, F>>>,
    /// Application configuration (policy summary source).
    pub cfg: Config,
    /// Shared live state (the same handle the pipeline maintains).
    pub state: Arc<Mutex<LiveState>>,
    /// Audit journal (`None` keeps the task journal-free, like the pipeline).
    pub journal: Option<Arc<Mutex<AuditJournal>>>,
    /// Policy overlay (kill switch + admin edits).
    pub policy: Arc<SharedPolicy>,
    /// Trigger channel from the pipeline. Shared so the supervised task can
    /// be rebuilt across restarts.
    pub triggers: Arc<Mutex<mpsc::Receiver<ConsultTrigger>>>,
    /// Approved orders toward the pipeline.
    pub orders: mpsc::Sender<ApprovedOrder>,
    /// Alert destination for consulted decisions.
    pub sink: S,
    /// Nansen client for smart-money enrichment (`None` degrades to
    /// [`SmartMoneyContext::unavailable`]).
    pub nansen: Option<Arc<NansenClient>>,
    /// Periodic review cadence, seconds (`STRATEGY_REVIEW_INTERVAL_SECS`).
    pub review_interval_secs: u64,
    /// Consult decision sequence (`s-<n>` correlation ids).
    seq: AtomicU64,
}

impl<P: Provider, F: Provider, S> ConsultTask<P, F, S> {
    /// Assemble a consult task over the shared daemon handles.
    #[allow(clippy::too_many_arguments)] // daemon wiring is explicit by design (SPEC-P20 §2)
    pub fn new(
        engine: Option<Arc<StrategyEngine<P, F>>>,
        cfg: Config,
        state: Arc<Mutex<LiveState>>,
        journal: Option<Arc<Mutex<AuditJournal>>>,
        policy: Arc<SharedPolicy>,
        triggers: Arc<Mutex<mpsc::Receiver<ConsultTrigger>>>,
        orders: mpsc::Sender<ApprovedOrder>,
        sink: S,
        nansen: Option<Arc<NansenClient>>,
        review_interval_secs: u64,
    ) -> Self {
        Self {
            engine,
            cfg,
            state,
            journal,
            policy,
            triggers,
            orders,
            sink,
            nansen,
            review_interval_secs,
            seq: AtomicU64::new(0),
        }
    }
}

impl<P, F, S> ConsultTask<P, F, S>
where
    P: Provider + Send + Sync + 'static,
    F: Provider + Send + Sync + 'static,
    S: AlertSink + Send + Sync + 'static,
{
    /// Run the consult loop until `shutdown` flips or the trigger channel
    /// closes. With no engine the task returns immediately (inert).
    pub async fn run(self, mut shutdown: watch::Receiver<bool>) {
        if self.engine.is_none() {
            tracing::info!("consult task inert (strategy engine unavailable)");
            return;
        }
        if *shutdown.borrow() {
            return;
        }
        let interval_secs = self.review_interval_secs.max(1);
        let interval = Duration::from_secs(interval_secs);
        let mut ticker = tokio::time::interval_at(tokio::time::Instant::now() + interval, interval);
        ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        tracing::info!(review_interval_secs = interval_secs, "consult task started");

        loop {
            tokio::select! {
                biased;
                change = shutdown.changed() => {
                    if change.is_err() || *shutdown.borrow() {
                        break;
                    }
                }
                _ = ticker.tick() => {
                    self.handle_trigger(ConsultTrigger::Periodic).await;
                }
                trigger = next_trigger(&self.triggers) => {
                    match trigger {
                        Some(trigger) => self.handle_trigger(trigger).await,
                        None => {
                            tracing::info!("trigger channel closed; consult task stopping");
                            break;
                        }
                    }
                }
            }
        }
    }

    /// One trigger to completion: filter, build the input, journal the intent
    /// (audit-before-action), consult, then map -> gate -> act.
    async fn handle_trigger(&self, trigger: ConsultTrigger) {
        let now_ms = unix_ms();
        let Some((account, markets)) = self.snapshot().await else {
            tracing::debug!(
                trigger = trigger.label(),
                "consult skipped: no account snapshot yet"
            );
            return;
        };
        let thresholds = thresholds(&self.cfg);
        let Some(focus) = trigger_focus(&trigger, &account, &markets, &thresholds) else {
            tracing::debug!(
                trigger = trigger.label(),
                "consult skipped: trigger filtered out"
            );
            return;
        };
        let Some(engine) = &self.engine else {
            return;
        };
        let decision_id = self.next_decision_id();

        // Smart-money context (cache-first; degrade on any error/timeout).
        let asset = markets
            .iter()
            .find(|market| market.id == focus)
            .map(|market| market.symbol.clone())
            .unwrap_or_else(|| focus.0.to_string());
        let sm = self.smart_money(&asset, &chain_for(&asset)).await;

        let input = ConsultInput {
            account: account.clone(),
            markets: markets.clone(),
            focus_market: focus,
            policy: policy_summary(&self.cfg),
            sm,
            reflex: self.reflex_summary().await,
        };
        let input_hash = consult_input_hash(&input, &trigger, now_ms);

        // Audit-before-action (P00 invariant #2): the STRATEGY intent lands
        // before the consult call.
        self.journal_intent(&trigger, &input, &input_hash, &decision_id, now_ms)
            .await;

        let outcome = match engine.consult(&input, now_ms).await {
            Ok(outcome) => outcome,
            Err(err) => {
                tracing::warn!(
                    market_id = focus.0,
                    trigger = trigger.label(),
                    error = %err,
                    "strategy consult failed"
                );
                self.journal_outcome(
                    focus,
                    &input_hash,
                    json!({
                        "action": "consult",
                        "decision_id": decision_id,
                        "market_id": focus.0,
                        "trigger": trigger.label(),
                    }),
                    json!({ "verdict": "error" }),
                    json!({
                        "status": "error",
                        "error": err.to_string(),
                        "mode": mode_label(self.cfg.execution.mode),
                    }),
                    now_ms,
                )
                .await;
                return;
            }
        };
        self.act_on_outcome(&input, &input_hash, &decision_id, &outcome, now_ms)
            .await;
    }

    /// Map the decision to an [`Intent`], run the same policy gate the bot's
    /// `/risk` path uses (`PolicySource::Strategy`), and act:
    ///
    /// - allow + sized order -> send [`ApprovedOrder`] to the pipeline;
    /// - needs-approval / deny / escalate -> journal + alert only;
    /// - hold / no executable order -> journal (+ alert in Orange+).
    ///
    /// Every consulted decision in Orange+ alerts; needs-approval, deny and
    /// ESCALATE alert at any tier (SPEC-P20 §2.4–§2.5).
    async fn act_on_outcome(
        &self,
        input: &ConsultInput,
        input_hash: &str,
        decision_id: &str,
        outcome: &ConsultOutcome,
        now_ms: u64,
    ) {
        let decision = &outcome.decision;
        let market_id = MarketId(decision.market_id);
        let symbol = input
            .markets
            .iter()
            .find(|market| market.id == market_id)
            .map(|market| market.symbol.clone())
            .unwrap_or_else(|| market_id.0.to_string());
        let tier = tier_of(
            &input.account,
            &input.markets,
            market_id,
            &thresholds(&self.cfg),
        )
        .unwrap_or(RiskTier::Green);
        let action = action_label(decision.action);
        let decision_doc = consult_decision_json(decision_id, outcome);

        let (policy_verdict, execution, alert) = match decision.action {
            DecisionAction::Escalate => {
                let budget = outcome.provider_used == "budget";
                let status = if budget {
                    "escalate_budget"
                } else {
                    "escalate"
                };
                let text = format!(
                    "🧠 {}#{} strategy ESCALATE · {}",
                    symbol, market_id.0, decision.reason
                );
                (
                    json!({ "verdict": "escalate" }),
                    json!({
                        "status": status,
                        "mode": mode_label(self.cfg.execution.mode),
                        "budget_breach": budget,
                    }),
                    Some(strategy_alert(
                        market_id,
                        decision_id,
                        action,
                        status,
                        text,
                        now_ms,
                    )),
                )
            }
            DecisionAction::Hold => {
                let alert = (tier >= RiskTier::Orange).then(|| {
                    strategy_alert(
                        market_id,
                        decision_id,
                        action,
                        "hold",
                        format!(
                            "🧠 {}#{} strategy HOLD · {}",
                            symbol, market_id.0, decision.reason
                        ),
                        now_ms,
                    )
                });
                (
                    json!({ "verdict": "hold" }),
                    json!({ "status": "hold", "mode": mode_label(self.cfg.execution.mode) }),
                    alert,
                )
            }
            DecisionAction::Reduce | DecisionAction::Close | DecisionAction::AddCollateral => {
                self.gate_action(input, decision_id, decision, tier, &symbol, now_ms)
                    .await
            }
        };

        self.journal_outcome(
            market_id,
            input_hash,
            decision_doc,
            policy_verdict,
            execution,
            now_ms,
        )
        .await;
        if let Some(alert) = alert {
            self.send_alert(alert).await;
        }
    }

    /// The actionable half of [`Self::act_on_outcome`]: policy-gate the
    /// mapped intent and either queue an order or alert.
    #[allow(clippy::too_many_arguments)] // decision context is explicit by design (SPEC-P20 §2.4)
    async fn gate_action(
        &self,
        input: &ConsultInput,
        decision_id: &str,
        decision: &Decision,
        tier: RiskTier,
        symbol: &str,
        now_ms: u64,
    ) -> (Value, Value, Option<Alert>) {
        let market_id = MarketId(decision.market_id);
        let action = action_label(decision.action);
        let mode = mode_label(self.cfg.execution.mode);

        let Some(intent) = decision_intent(&input.account, decision) else {
            // Reduce against a missing/flat position (or missing amount): the
            // same "n/a" case the bot's `/risk` renders — nothing to gate.
            tracing::warn!(
                market_id = market_id.0,
                decision_id,
                "strategy decision has no resolvable intent; skipping the gate"
            );
            return (
                json!({ "verdict": "n/a" }),
                json!({ "status": "no_intent", "mode": mode }),
                None,
            );
        };

        let verdict = PolicyEngine::evaluate(
            &intent,
            &input.account,
            &policy_config(&self.cfg, self.policy.kill_switch()),
            &DayState { actions_today: 0 },
            &PolicyContext {
                source: PolicySource::Strategy,
                tier,
                market_id,
            },
        );
        let verdict_text_value = verdict_text(&verdict);
        let tier_text = tier_label(tier);

        match verdict {
            PolicyVerdict::Allow => {
                match size_order(&input.account, &input.markets, market_id, &intent) {
                    Some(order) => {
                        let order_doc = serde_json::to_value(&order).unwrap_or(Value::Null);
                        let size_text = order.size.to_string();
                        let approved = ApprovedOrder {
                            decision_id: decision_id.to_string(),
                            order,
                        };
                        match self.orders.send(approved).await {
                            Ok(()) => {
                                let alert = (tier >= RiskTier::Orange).then(|| {
                                    strategy_alert(
                                        market_id,
                                        decision_id,
                                        action,
                                        "allow: queued",
                                        format!(
                                            "🧠 {}#{} strategy {} · size {} queued for execution",
                                            symbol, market_id.0, action, size_text
                                        ),
                                        now_ms,
                                    )
                                });
                                (
                                    json!({ "verdict": verdict_text_value, "tier": tier_text, "order": order_doc }),
                                    json!({ "status": "queued", "mode": mode, "order": order_doc }),
                                    alert,
                                )
                            }
                            Err(err) => {
                                tracing::error!(
                                    market_id = market_id.0,
                                    error = %err,
                                    "strategy order channel closed; decision not queued"
                                );
                                (
                                    json!({ "verdict": verdict_text_value, "tier": tier_text, "order": order_doc }),
                                    json!({
                                        "status": "send_failed",
                                        "error": err.to_string(),
                                        "mode": mode,
                                    }),
                                    Some(strategy_alert(
                                        market_id,
                                        decision_id,
                                        action,
                                        "allow: send_failed",
                                        format!(
                                            "🧠 {}#{} strategy {} · order channel closed",
                                            symbol, market_id.0, action
                                        ),
                                        now_ms,
                                    )),
                                )
                            }
                        }
                    }
                    None => {
                        // AddCollateral has no pipeline path (orders are
                        // reduce-only) and a sizing miss means one lot/mark
                        // short — journal, alert in Orange+.
                        let alert = (tier >= RiskTier::Orange).then(|| {
                            strategy_alert(
                                market_id,
                                decision_id,
                                action,
                                "allow: no_order",
                                format!(
                                    "🧠 {}#{} strategy {} · no executable order (reduce-only pipeline)",
                                    symbol, market_id.0, action
                                ),
                                now_ms,
                            )
                        });
                        (
                            json!({ "verdict": verdict_text_value, "tier": tier_text, "order": Value::Null }),
                            json!({ "status": "no_order", "mode": mode }),
                            alert,
                        )
                    }
                }
            }
            PolicyVerdict::NeedsApproval { reason } => {
                // No keyboard from the daemon path (SPEC-P20 §2.4): journal +
                // alert only; the human can re-run `/risk` or `/close`.
                (
                    json!({ "verdict": verdict_text_value, "tier": tier_text, "reason": reason }),
                    json!({ "status": "needs_approval", "mode": mode }),
                    Some(strategy_alert(
                        market_id,
                        decision_id,
                        action,
                        "needs_approval",
                        format!(
                            "🧠 {}#{} strategy decision needs approval — use /approve or /risk · {}",
                            symbol, market_id.0, reason
                        ),
                        now_ms,
                    )),
                )
            }
            PolicyVerdict::Deny { reason } => (
                json!({ "verdict": verdict_text_value, "tier": tier_text, "reason": reason }),
                json!({ "status": "denied", "mode": mode }),
                Some(strategy_alert(
                    market_id,
                    decision_id,
                    action,
                    "deny",
                    format!(
                        "🧠 {}#{} strategy {} denied: {}",
                        symbol, market_id.0, action, reason
                    ),
                    now_ms,
                )),
            ),
        }
    }

    /// Live snapshot (account + markets), or `None` before the first account
    /// event.
    async fn snapshot(&self) -> Option<(AccountState, Vec<Market>)> {
        let state = self.state.lock().await;
        let account = state.account.clone()?;
        Some((account, state.markets.clone()))
    }

    /// Next consult correlation id (`s-<n>`).
    fn next_decision_id(&self) -> String {
        format!("s-{}", self.seq.fetch_add(1, Ordering::Relaxed) + 1)
    }

    /// Cache-first smart-money context for `asset` (SPEC-P20 §2.2).
    async fn smart_money(&self, asset: &str, chain: &str) -> SmartMoneyContext {
        let Some(client) = &self.nansen else {
            return SmartMoneyContext::unavailable(asset);
        };
        match tokio::time::timeout(
            SM_FETCH_TIMEOUT,
            client.smart_money_context(asset, chain, unix_ms()),
        )
        .await
        {
            Ok(context) => context,
            Err(_) => {
                tracing::warn!(
                    asset = %asset,
                    timeout_secs = SM_FETCH_TIMEOUT.as_secs(),
                    "smart-money fetch timed out; degrading to unavailable"
                );
                SmartMoneyContext::unavailable(asset)
            }
        }
    }

    /// Recent reflex actions from the journal (newest last).
    async fn reflex_summary(&self) -> ReflexSummary {
        let Some(journal) = &self.journal else {
            return ReflexSummary::default();
        };
        let entries = {
            let guard = journal.lock().await;
            match guard.read_entries(0, REFLEX_SCAN_LIMIT) {
                Ok(entries) => entries,
                Err(err) => {
                    tracing::warn!(error = %err, "reflex summary journal read failed");
                    return ReflexSummary::default();
                }
            }
        };
        reflex_summary_from(&entries, REFLEX_SUMMARY_LIMIT)
    }

    /// Journal one STRATEGY intent (audit-before-action).
    async fn journal_intent(
        &self,
        trigger: &ConsultTrigger,
        input: &ConsultInput,
        input_hash: &str,
        decision_id: &str,
        now_ms: u64,
    ) {
        let Some(journal) = &self.journal else {
            return;
        };
        let record = IntentRecord {
            trigger: Trigger::Strategy,
            account: account_label(&self.cfg),
            market_id: Some(input.focus_market.0),
            input_hash: input_hash.to_string(),
            decision: json!({
                "action": "consult",
                "decision_id": decision_id,
                "focus_market": input.focus_market.0,
                "trigger": trigger.label(),
                "policy": serde_json::to_value(&input.policy).unwrap_or(Value::Null),
            }),
            policy_verdict: json!({ "verdict": "pending", "note": "consult requested" }),
        };
        let mut guard = journal.lock().await;
        if let Err(err) = guard.record_intent(&record, journal_ts(now_ms)) {
            tracing::error!(
                error = %err,
                decision_id,
                "strategy intent journal write failed; proceeding"
            );
        }
    }

    /// Journal the STRATEGY outcome of one consult.
    async fn journal_outcome(
        &self,
        market_id: MarketId,
        input_hash: &str,
        decision: Value,
        policy_verdict: Value,
        execution: Value,
        now_ms: u64,
    ) {
        let Some(journal) = &self.journal else {
            return;
        };
        let record = OutcomeRecord {
            trigger: Trigger::Strategy,
            account: account_label(&self.cfg),
            market_id: Some(market_id.0),
            input_hash: input_hash.to_string(),
            decision,
            policy_verdict,
            execution,
        };
        let mut guard = journal.lock().await;
        if let Err(err) = guard.record_outcome(&record, journal_ts(now_ms)) {
            tracing::error!(error = %err, "strategy outcome journal write failed");
        }
    }

    /// Deliver one alert; failures are logged, never fatal.
    async fn send_alert(&self, alert: Alert) {
        if let Err(err) = self.sink.send(&alert).await {
            tracing::warn!(
                error = %err,
                market_id = alert.market_id.map(|market| market.0),
                "strategy alert delivery failed"
            );
        }
    }
}

/// Next trigger from the shared receiver (`None` once every sender dropped).
async fn next_trigger(triggers: &Mutex<mpsc::Receiver<ConsultTrigger>>) -> Option<ConsultTrigger> {
    triggers.lock().await.recv().await
}

/// Decision -> [`Intent`] mapping, identical to the bot `/risk` path
/// (SPEC-P20 §2.4): REDUCE scales by the consulted position's size, CLOSE and
/// ADD_COLLATERAL map directly (an amount is required), HOLD/ESCALATE produce
/// no intent, and a REDUCE against a missing or flat position resolves to
/// `None` (rendered as `n/a` by the bot).
pub(crate) fn decision_intent(account: &AccountState, decision: &Decision) -> Option<Intent> {
    let market_id = MarketId(decision.market_id);
    match decision.action {
        DecisionAction::Reduce => {
            let position = account
                .positions
                .iter()
                .find(|position| position.market_id == market_id)?;
            let amount = decision.amount?;
            if position.size.is_zero() {
                return None;
            }
            Some(Intent::Reduce {
                fraction: amount / position.size.abs(),
                reason: decision.reason.clone(),
            })
        }
        DecisionAction::Close => Some(Intent::Close {
            reason: decision.reason.clone(),
        }),
        DecisionAction::AddCollateral => {
            let amount = decision.amount?;
            Some(Intent::AddCollateral {
                amount,
                reason: decision.reason.clone(),
            })
        }
        DecisionAction::Hold | DecisionAction::Escalate => None,
    }
}

/// Resolve the consult focus for a trigger against the live snapshot; `None`
/// filters the trigger out (SPEC-P20 §2 trigger filtering).
fn trigger_focus(
    trigger: &ConsultTrigger,
    account: &AccountState,
    markets: &[Market],
    thresholds: &RiskThresholds,
) -> Option<MarketId> {
    match trigger {
        ConsultTrigger::YellowEntry { market_id } => {
            tier_of(account, markets, *market_id, thresholds).map(|_| *market_id)
        }
        ConsultTrigger::PostReflexReduce { market_id, tier } => {
            if *tier < RiskTier::Orange {
                return None;
            }
            tier_of(account, markets, *market_id, thresholds).map(|_| *market_id)
        }
        ConsultTrigger::Periodic => riskiest_at_or_above_yellow(account, markets, thresholds)
            .map(|(market_id, _)| market_id),
    }
}

/// Position tier for `market_id` against the snapshot, when derivable
/// (position and market both present, distance computable).
fn tier_of(
    account: &AccountState,
    markets: &[Market],
    market_id: MarketId,
    thresholds: &RiskThresholds,
) -> Option<RiskTier> {
    let position = account
        .positions
        .iter()
        .find(|position| position.market_id == market_id)?;
    let market = markets.iter().find(|market| market.id == market_id)?;
    risk::distance_to_liq_pct(position, market).map(|distance| risk::tier(distance, thresholds))
}

/// The riskiest position at or above Yellow (smallest distance first;
/// ties broken by market id for determinism).
fn riskiest_at_or_above_yellow(
    account: &AccountState,
    markets: &[Market],
    thresholds: &RiskThresholds,
) -> Option<(MarketId, RiskTier)> {
    account
        .positions
        .iter()
        .filter_map(|position| {
            let market = markets
                .iter()
                .find(|market| market.id == position.market_id)?;
            let distance = risk::distance_to_liq_pct(position, market)?;
            let tier = risk::tier(distance, thresholds);
            (tier >= RiskTier::Yellow).then_some((tier, distance, position.market_id))
        })
        .min_by(|left, right| left.1.cmp(&right.1).then_with(|| left.2.0.cmp(&right.2.0)))
        .map(|(tier, _, market_id)| (market_id, tier))
}

/// Size the reduce-only order for an allowed intent (same sizing and slippage
/// cap as the reflex engine and the bot's `/close`). `AddCollateral` has no
/// pipeline path and sizes to `None`.
fn size_order(
    account: &AccountState,
    markets: &[Market],
    market_id: MarketId,
    intent: &Intent,
) -> Option<OrderRequest> {
    let position = account
        .positions
        .iter()
        .find(|position| position.market_id == market_id)?;
    let market = markets.iter().find(|market| market.id == market_id)?;
    match intent {
        Intent::Reduce { fraction, .. } => {
            reduce_by_fraction(position, *fraction, market, REFLEX_SLIPPAGE_BPS)
        }
        Intent::Close { .. } => {
            reduce_by_fraction(position, Decimal::ONE, market, REFLEX_SLIPPAGE_BPS)
        }
        Intent::AddCollateral { .. } | Intent::Alert { .. } => None,
    }
}

/// Render recent reflex actions from journal entries (newest last, at most
/// `limit` lines). Non-reflex entries are ignored.
fn reflex_summary_from(entries: &[AuditEntry], limit: usize) -> ReflexSummary {
    let mut actions: Vec<String> = entries
        .iter()
        .filter(|entry| entry.trigger == Trigger::Reflex)
        .filter_map(reflex_action_line)
        .collect();
    if actions.len() > limit {
        actions.drain(..actions.len() - limit);
    }
    ReflexSummary { actions }
}

/// `d-<n> #<market> <action> · <status>` for one reflex journal entry.
fn reflex_action_line(entry: &AuditEntry) -> Option<String> {
    let decision_id = entry.decision.get("decision_id")?.as_str()?;
    let market_id = entry.market_id?;
    let action = entry
        .decision
        .get("action")
        .and_then(Value::as_str)
        .unwrap_or("action");
    let status = entry
        .execution
        .get("status")
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    Some(format!("{decision_id} #{market_id} {action} · {status}"))
}

