/// Journal timestamp from the injected clock (wall clock as a fallback).
fn journal_ts(now_ms: u64) -> DateTime<Utc> {
    i64::try_from(now_ms)
        .ok()
        .and_then(DateTime::from_timestamp_millis)
        .unwrap_or_else(Utc::now)
}

/// Wall-clock milliseconds since the Unix epoch (0 before 1970).
fn unix_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| u64::try_from(elapsed.as_millis()).unwrap_or(u64::MAX))
        .unwrap_or(0)
}

/// Best-effort Nansen chain name for a market symbol (cross-venue data
/// chains; the fallback is the lowercased symbol).
fn chain_for(symbol: &str) -> String {
    let uppercase = symbol.to_ascii_uppercase();
    match uppercase.as_str() {
        "ETH" | "WETH" => "ethereum".to_string(),
        "BTC" | "WBTC" => "bitcoin".to_string(),
        "SOL" => "solana".to_string(),
        "AVAX" => "avalanche".to_string(),
        "MON" => "monad".to_string(),
        _ => symbol.to_ascii_lowercase(),
    }
}

