#!/usr/bin/env bash
# build-deploy.sh — assemble the Vercel deployment for Sentinel's live product.
#
# Layout produced in deploy/vercel/:
#   index.html            the dashboard (unchanged)
#   api/state.js          snapshot + LIVE Perpl testnet chain/ticker data
#   api/decisions.js      decision-feed snapshot
#   api/audit/verify.js   journal verification snapshot
#   api/breaker-status.js breaker snapshot
#   api/backtest.js       backtest report snapshot
#   api/nansen/spend.js   Nansen x402 spend snapshot
#   api-data/*.json       the captured snapshots (bundled into the functions)
#   vercel.json           routing + headers
#
# Usage: bash tools/deploy/build-deploy.sh [--refresh]
set -euo pipefail
cd "$(dirname "$0")/../.."

SRC=dashboard/index.html
OUT=deploy/vercel
DATA=$OUT/api-data

if [ "${1:-}" = "--refresh" ]; then
  echo "[deploy] refreshing snapshots from http://localhost:8081 ..."
  mkdir -p "$DATA"
  declare -A EP=(
    [state]=/api/state
    [decisions]="/api/decisions?limit=20"
    [audit-verify]=/api/audit/verify
    [breaker-status]=/api/breaker-status
    [backtest]=/api/backtest
    [nansen-spend]=/api/nansen/spend
  )
  for k in "${!EP[@]}"; do
    code=$(curl -s -o "$DATA/$k.json" -w "%{http_code}" -m 15 "http://localhost:8081${EP[$k]}")
    echo "  $k -> $code"
  done
fi

[ -f "$DATA/state.json" ] || { echo "no snapshots in $DATA — run with --refresh while the daemon is up"; exit 1; }

mkdir -p "$OUT/api/audit" "$OUT/api/nansen"
cp "$SRC" "$OUT/index.html"
echo "[deploy] index.html copied ($(wc -c < "$OUT/index.html") bytes)"

# ---- snapshot-serving functions -------------------------------------------
# Each function inlines its snapshot at build time so the deployment is
# self-contained (no filesystem reads at runtime).
mkfn() { # <outfile> <datafile> <fnname>
  local out="$1" data="$2" name="$3"
  {
    echo "// Auto-generated by tools/deploy/build-deploy.sh — do not edit by hand."
    echo "const SNAPSHOT = $(cat "$data");"
    echo ""
    echo "export default function handler(req, res) {"
    echo "  res.setHeader('Access-Control-Allow-Origin', '*');"
    echo "  res.setHeader('Cache-Control', 'public, max-age=15, s-maxage=15');"
    echo "  res.status(200).json(SNAPSHOT);"
    echo "}"
  } > "$out"
  echo "  wrote $out"
}

mkfn "$OUT/api/decisions.js"        "$DATA/decisions.json"      decisions
mkfn "$OUT/api/audit/verify.js"     "$DATA/audit-verify.json"   auditverify
mkfn "$OUT/api/breaker-status.js"   "$DATA/breaker-status.json" breakerstatus
mkfn "$OUT/api/backtest.js"         "$DATA/backtest.json"       backtest
mkfn "$OUT/api/nansen/spend.js"     "$DATA/nansen-spend.json"   nansenspend

# ---- state.js: merge snapshot with LIVE Perpl testnet data -----------------
python3 - "$DATA/state.json" tools/deploy/state.template.js "$OUT/api/state.js" <<'PY'
import sys, json
snap_path, tmpl_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
snap = json.load(open(snap_path))
tmpl = open(tmpl_path).read()
open(out_path, 'w').write(tmpl.replace('__SNAPSHOT__', json.dumps(snap)))
print("  wrote", out_path, "(state.js, live merge)")
PY

# Remove the intermediate state.json so it is not deployed twice.
rm -f "$DATA/state.json"

echo "[deploy] snapshot functions written"
ls -R "$OUT" | head -30
